void SSD1306_SetPos(uint8_t x, uint8_t y)
{
  SSD1306_WriteCmd(0xb0 + y);
  SSD1306_WriteCmd(((x & 0xf0) >> 4) | 0x10);
  SSD1306_WriteCmd((x & 0x0f));
}

void SSD1306_Fill(uint8_t fill_Data)
{
  unsigned char m, n;
  for (m = 0; m < 8; m++) {
    SSD1306_WriteCmd(0xb0 + m);
    SSD1306_WriteCmd(0x00);
    SSD1306_WriteCmd(0x10);
    for (n = 0; n < 128; n++)
      SSD1306_WiteData(fill_Data);
  }
}

void SSD1306_CLS(void)
{
  SSD1306_Fill(0x00);
}

void SSD1306_ShowStr(uint8_t x, uint8_t y, uint8_t ch[], uint8_t TextSize)
{
  unsigned char c = 0, i = 0, j = 0;
  switch (TextSize) {
  case 8:
    while (ch[j] != '\0') {
      c = ch[j] - 32;
      if (x > 126) { x = 0; y++; }
      SSD1306_SetPos(x, y);
      for (i = 0; i < 6; i++) SSD1306_WiteData(F6x8[c][i]);
      x += 6; j++;
    }
    break;
  case 16:
    y *= 2;
    while (ch[j] != '\0') {
      c = ch[j] - 32;
      if (x > 120) { x = 0; y++; }
      SSD1306_SetPos(x, y);
      for (i = 0; i < 8; i++) SSD1306_WiteData(F8X16[c * 16 + i]);
      SSD1306_SetPos(x, y + 1);
      for (i = 0; i < 8; i++) SSD1306_WiteData(F8X16[c * 16 + i + 8]);
      x += 8; j++;
    }
    break;
  }
}

